/* =========================================
   단일 위치 결과
========================================= */

function createSingleResult(
  profile,
  position
) {

  const context =
    POSITION_DOMAIN[
      position
    ];


  if (!context) {

    return profile.direct;

  }


  const domainResult =
    CATEGORY_BY_DOMAIN[
      profile.category
    ]?.[
      context.domain
    ] ?? "";


  return `
    ${profile.direct}
    ${context.text}에서는
    ${domainResult}
  `;

}


/* =========================================
   관계형 신살 결과
========================================= */

function createRelationResult(
  profile,
  positions
) {

  const labels =
    positions

      .map(
        position =>
          POSITION_LABELS[
            position
          ] ?? position
      )

      .join(" ↔ ");


  const contexts =
    positions

      .map(
        position =>
          POSITION_DOMAIN[
            position
          ]?.text
      )

      .filter(Boolean)

      .join("과 ");


  return `
    ${profile.direct}
    이번 원국에서는 ${labels} 사이에 성립하므로
    ${contexts}가 서로 맞물릴 때
    이 패턴을 특히 체감하기 쉽습니다.
  `;

}


/* =========================================
   최종 해석
========================================= */

export function buildSinsalReading(
  item
) {

  const profile =
    STAR_PROFILE[
      item.name
    ] ?? DEFAULT_PROFILE;


  const base =
    TWELVE_SINSAL_DESCRIPTIONS[
      item.name
    ]

    ??

    SINSAL_DESCRIPTIONS[
      item.name
    ]

    ??

    {
      summary:
        "전통 명리학에서 사용하는 신살·길성입니다.",

      meaning:
        "",

      positive:
        "전체 원국과 함께 장점으로 활용할 수 있습니다.",

      caution:
        "이 요소 하나만으로 결과를 단정하지 않습니다."
    };


  const positions =
    item.positions ?? [];


  const result =
    positions.length >= 2

      ? createRelationResult(
          profile,
          positions
        )

      : createSingleResult(
          profile,
          positions[0]
        );


  const positionLabel =
    positions.length

      ? positions
          .map(
            position =>
              POSITION_LABELS[
                position
              ] ?? position
          )
          .join(" · ")

      : item.pillar;


  return {

    summary:
      base.summary,

    result:
      result
        .replace(/\s+/g, " ")
        .trim(),

    strength:
      base.positive,

    caution:
      base.caution,

    positionLabel,

    basis:
      `현재 원국에서 ${item.name}이 ${positionLabel}에 성립한 위치와 ${item.name}의 고유 작용을 함께 적용한 해석입니다.`

  };

}