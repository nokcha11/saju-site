export function getDailyDomainReading(
  result,
  key,
  points
) {
  const band =
    points >= 75
      ? 0
      : points >= 60
        ? 1
        : 2;

  const [title, reading, action] =
    READINGS[key][band];

  const contributions = Object.entries(
    result.contributions ?? {}
  )
    .filter(
      ([, values]) => Number.isFinite(values[key])
    )
    .sort(
      (a, b) => b[1][key] - a[1][key]
    );

  const strongestBackground =
    contributions[0];

  const background =
    strongestBackground &&
    strongestBackground[1][key] > 0
      ? `이 영역의 십성 점수에는 ${strongestBackground[0]} 배경이 가장 크게 반영되었습니다.`
      : "원국과 각 운의 기운을 함께 비교한 결과입니다.";

  return {
    title,
    reading,
    action,
    background
  };
}

export function getDailyActionPlan(result) {
  const ranking = Object.entries(result.scores)
    .filter(
      ([key]) => DAILY_DOMAINS[key]
    )
    .sort(
      (a, b) => b[1] - a[1]
    );

  const recommended = ranking
    .slice(0, 3)
    .map(([key, raw]) => {
      const points =
        result.scoreSummary?.domainScores?.[key]
        ?? referenceScore(raw);

      const reading =
        getDailyDomainReading(
          result,
          key,
          points
        );

      return {
        label: DAILY_DOMAINS[key].label,

        text: reading.action.replace(
          /^오늘 할 일:\s*/,
          ""
        )
      };
    });

  const cautions = ranking
    .slice(-3)
    .reverse()
    .map(([key]) => ({
      label: DAILY_DOMAINS[key].label,
      text: DAILY_DOMAINS[key].careful
    }));

  if (
    result.relations.some(
      relation => relation.type === "충"
    )
  ) {
    cautions.unshift({
      label: "일정 · 소통",

      text:
        "운의 비교에 충 신호가 있으므로 일정 변경과 의견 차이에 여유를 두세요. 중요한 약속과 전달 내용은 한 번 더 확인하세요."
    });
  }

  return {
    recommended,
    cautions: cautions.slice(0, 3)
  };
}