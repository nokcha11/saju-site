/* =========================================
   순서
========================================= */

const PILLAR_ORDER = {

  year: 0,
  month: 1,
  day: 2,
  hour: 3

};


/* =========================================
   position → pillar key
========================================= */

function getPillarKey(
  position
) {

  if (
    position.startsWith(
      "year"
    )
  ) {
    return "year";
  }


  if (
    position.startsWith(
      "month"
    )
  ) {
    return "month";
  }


  if (
    position.startsWith(
      "day"
    )
  ) {
    return "day";
  }


  if (
    position.startsWith(
      "hour"
    )
  ) {
    return "hour";
  }


  return "";

}


/* =========================================
   두 위치 조합 해석
========================================= */

function getPairResult(
  positions
) {

  if (
    positions.length !== 2
  ) {
    return "";
  }


  const keys =
    positions

      .map(
        getPillarKey
      )

      .sort(
        (a, b) =>
          PILLAR_ORDER[a] -
          PILLAR_ORDER[b]
      );


  return (

    PAIR_RESULTS[
      `${keys[0]}-${keys[1]}`
    ]

    ?? ""

  );

}


/* =========================================
   오행 관계 설명
========================================= */

function getElementNote(
  item
) {

  if (
    !item.element
  ) {
    return "";
  }


  const elementLabel =
    ELEMENT_LABELS[
      item.element
    ]

    ?? item.element;


  if (
    item.name === "합"
  ) {

    return `

      전통적으로 합화의 방향은
      ${elementLabel}로 보지만,
      실제 합화 성립 여부는
      월령과 주변 구조를 별도로 확인해야 합니다.

    `
      .replace(/\s+/g, " ")
      .trim();

  }


  if (
    [
      "반합",
      "삼합",
      "방합"
    ].includes(
      item.name
    )
  ) {

    return `

      이 관계는
      ${elementLabel} 방향으로
      기운을 모으는 관계로 봅니다.

      다만 실제 세력의 크기는
      월령과 다른 합충까지 함께 계산해야 합니다.

    `
      .replace(/\s+/g, " ")
      .trim();

  }


  return "";

}


/* =========================================
   최종 결과
========================================= */

export function buildRelationReading(
  item
) {

  const base =
    RELATION_INFO[
      item.name
    ]

    ??

    {
      result:
        "두 영역 사이에 전통 명리학적 관계가 성립합니다.",

      strength:
        "관계가 작용하는 두 영역을 함께 살펴보는 것이 좋습니다.",

      caution:
        "이 관계 하나만으로 길흉을 단정하지 않습니다."
    };


  /* =====================================
     일지 申 ↔ 년지 卯
     형태로 표시
  ===================================== */

  const locationLabel =
    (
      item.members
      ?? []
    )

      .map(
        member =>

          `${

            POSITION_LABELS[
              member.position
            ]

            ?? member.position

          } ${member.symbol}`

      )

      .join(" ↔ ");


  const areaText =
    item.positions

      .map(
        position =>

          POSITION_AREAS[
            position
          ]

          ?? position

      )

      .join("과 ");


  const pairResult =
    getPairResult(
      item.positions
    );


  const elementNote =
    getElementNote(
      item
    );


  const result =
    `

      현재 원국에서는

      ${locationLabel || areaText}

      사이에

      ${item.displayName ?? item.name}

      관계가 성립합니다.

      ${base.result}

      ${pairResult}

      ${elementNote}

    `
      .replace(/\s+/g, " ")
      .trim();


  return {

    locationLabel,

    result,

    strength:
      base.strength,

    caution:
      base.caution,

    basis:
      `${item.symbols} 관계를 ${item.basis} 기준으로 판정했습니다.`

  };

}