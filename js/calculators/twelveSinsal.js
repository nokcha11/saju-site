/* =========================================
   년지가 어느 그룹인지 찾기
========================================= */

function getGroup(
  yearBranch
) {

  for (
    const [
      groupName,
      branches
    ]
    of Object.entries(GROUPS)
  ) {

    if (
      branches.includes(
        yearBranch
      )
    ) {

      return groupName;

    }

  }


  return null;

}


/* =========================================
   12신살 반환
========================================= */

export function getTwelveSinsal(
  yearBranch,
  targetBranch
) {

  const group =
    getGroup(
      yearBranch
    );


  if (!group) {

    return "";

  }


  return (
    TWELVE_SINSAL[
      group
    ][
      targetBranch
    ]
    ?? ""
  );

}