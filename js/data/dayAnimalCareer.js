/* =========================================
   중복 제거
========================================= */

function unique(
  values
) {

  return [
    ...new Set(values)
  ];

}


/* =========================================
   최종 직업 해석
========================================= */

export function buildDayAnimalCareer({

  element,
  dayBranch

}) {

  const elementCareer =
    ELEMENT_CAREER[
      element
    ];


  const animalCareer =
    ANIMAL_CAREER[
      dayBranch
    ];


  if (
    !elementCareer ||
    !animalCareer
  ) {

    return null;

  }


  return {

    result:
      `${animalCareer.workStyle} ${elementCareer.style}`,

    strengths:
      unique([
        ...animalCareer.strengths,
        ...elementCareer.strengths
      ]),

    fields:
      unique([
        ...animalCareer.fields,
        ...elementCareer.fields
      ]),

    avoid:
      animalCareer.avoid

  };

}